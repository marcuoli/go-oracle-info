//go:build ignore

// Generate the source API reference. Run from the module root.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

const (
	module    = "github.com/marcuoli/go-oracle-info"
	reference = "docs/api-reference.md"
)

type listedPackage struct {
	Dir, ImportPath string
	GoFiles         []string
}

type declarations struct {
	types, functions, methods []string
	constants, variables      []string
}

func main() {
	check := flag.Bool("check", false, "check the committed reference against the source")
	flag.Parse()

	packages, err := listPackages()
	if err != nil {
		log.Fatal(err)
	}
	document, err := render(packages)
	if err != nil {
		log.Fatal(err)
	}
	if *check {
		prior, err := os.ReadFile(reference)
		if err != nil {
			log.Fatal(err)
		}
		if !bytes.Equal(prior, document) {
			log.Fatal(reference + " is stale. Run go run ./scripts/api_reference.go")
		}
		return
	}
	if err := os.WriteFile(reference, document, 0o644); err != nil {
		log.Fatal(err)
	}
}

func listPackages() ([]listedPackage, error) {
	command := exec.Command("go", "list", "-json", "./...")
	command.Stderr = os.Stderr
	output, err := command.Output()
	if err != nil {
		return nil, err
	}
	decoder := json.NewDecoder(bytes.NewReader(output))
	var packages []listedPackage
	for {
		var p listedPackage
		err := decoder.Decode(&p)
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		packages = append(packages, p)
	}
	if len(packages) == 0 || packages[0].ImportPath != module {
		return nil, fmt.Errorf("run from the %s module root", module)
	}
	return packages, nil
}

func render(packages []listedPackage) ([]byte, error) {
	var document bytes.Buffer
	document.WriteString("# Public Go API reference\n\n")
	document.WriteString("Generated by `go run ./scripts/api_reference.go`. See [the fact API inventory](fact-apis.md) for recommended entry points, compatibility names, and source semantics.\n\n")
	document.WriteString("Signatures and public type fields come from the module's production Go source. The exported constants and variables are listed by name. Use `go doc` to inspect their values and comments.\n\n")
	var public, supporting []listedPackage
	for _, p := range packages {
		path := packagePath(p.ImportPath)
		if strings.HasPrefix(path, "internal/") || strings.HasPrefix(path, "examples/") {
			supporting = append(supporting, p)
		} else {
			public = append(public, p)
		}
	}
	fmt.Fprintf(&document, "## Index\n\n%d public packages. The support packages and executable examples are listed below.\n\n", len(public))
	for _, p := range public {
		name := packagePath(p.ImportPath)
		fmt.Fprintf(&document, "- [%s](#%s)\n", name, strings.ReplaceAll(name, "/", ""))
	}
	for _, p := range public {
		d, err := readDeclarations(p)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&document, "\n## %s\n\n`%s`\n", packagePath(p.ImportPath), p.ImportPath)
		writeBlock(&document, "Types", d.types)
		writeBlock(&document, "Functions", d.functions)
		writeBlock(&document, "Methods", d.methods)
		writeNames(&document, "Constants", d.constants)
		writeNames(&document, "Variables", d.variables)
	}
	document.WriteString("\n## Internal packages and examples\n\n")
	for _, p := range supporting {
		fmt.Fprintf(&document, "- `%s`\n", packagePath(p.ImportPath))
	}
	return document.Bytes(), nil
}

func packagePath(importPath string) string {
	if importPath == module {
		return "oracleinfo"
	}
	return strings.TrimPrefix(importPath, module+"/")
}

func readDeclarations(p listedPackage) (declarations, error) {
	var result declarations
	for _, name := range p.GoFiles {
		fileSet := token.NewFileSet()
		file, err := parser.ParseFile(fileSet, filepath.Join(p.Dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return declarations{}, err
		}
		ast.FileExports(file)
		for _, declaration := range file.Decls {
			switch node := declaration.(type) {
			case *ast.FuncDecl:
				node.Body = nil
				if node.Recv == nil {
					result.functions = append(result.functions, formatNode(node))
					continue
				}
				receiver := strings.TrimPrefix(formatNode(node.Recv.List[0].Type), "*")
				base, _, _ := strings.Cut(receiver, "[")
				if ast.IsExported(base) {
					result.methods = append(result.methods, formatNode(node))
				}
			case *ast.GenDecl:
				for _, spec := range node.Specs {
					switch value := spec.(type) {
					case *ast.TypeSpec:
						one := &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{value}}
						result.types = append(result.types, formatNode(one))
					case *ast.ValueSpec:
						for _, name := range value.Names {
							switch node.Tok {
							case token.CONST:
								result.constants = append(result.constants, name.Name)
							case token.VAR:
								result.variables = append(result.variables, name.Name)
							}
						}
					}
				}
			}
		}
	}
	return result, nil
}

func formatNode(node ast.Node) string {
	var output bytes.Buffer
	if err := format.Node(&output, token.NewFileSet(), node); err != nil {
		log.Fatal(err)
	}
	return output.String()
}

func writeBlock(document *bytes.Buffer, title string, items []string) {
	if len(items) == 0 {
		return
	}
	slices.Sort(items)
	fmt.Fprintf(document, "\n### %s\n\n~~~go\n%s\n~~~\n", title, strings.Join(items, "\n"))
}

func writeNames(document *bytes.Buffer, title string, names []string) {
	if len(names) == 0 {
		return
	}
	slices.Sort(names)
	fmt.Fprintf(document, "\n### %s\n\n", title)
	for _, name := range names {
		fmt.Fprintf(document, "- `%s`\n", name)
	}
}
